import { sections, options } from './config.js'

const CONFIG_KEY = 'laos_visa_email_config'

// 读取本机保存的邮箱配置（仅 localStorage，不上传服务器）
export function loadConfig() {
  try {
    const raw = localStorage.getItem(CONFIG_KEY)
    return raw ? JSON.parse(raw) : { serviceId: '', templateId: '', publicKey: '', toEmail: '' }
  } catch {
    return { serviceId: '', templateId: '', publicKey: '', toEmail: '' }
  }
}

export function saveConfig(config) {
  localStorage.setItem(CONFIG_KEY, JSON.stringify(config))
}

export function clearConfig() {
  localStorage.removeItem(CONFIG_KEY)
}

export function isConfigured(config) {
  return Boolean(config.serviceId && config.templateId && config.publicKey && config.toEmail)
}

// 护照号码格式校验：
// - 中国护照（普通 E / 旧版 G / 外交 D / 公务 S / 公务普通 P）：1 位字母 + 8 位数字
// - 其他国家：ICAO 9303 通用规则，5-17 位字母数字（各国格式差异大，做宽松校验）
function validatePassportNo(values, t) {
  const passportNo = String(values.passportNo || '').trim().toUpperCase()
  if (!passportNo) return null // 空值走必填校验

  const isCN = values.nationality === 'China' || values.countryOfPassport === 'China'
  if (isCN) {
    return /^[EGDSP][0-9]{8}$/.test(passportNo) ? null : t.passportFormatCN
  }
  return /^[A-Z0-9]{5,17}$/.test(passportNo) ? null : t.passportFormat
}

// 表单校验：必填项、日期逻辑、护照格式、声明勾选
export function validate(values, t) {
  const errors = {}

  sections.forEach((section) => {
    section.fields.forEach((field) => {
      const value = String(values[field.name] ?? '').trim()
      if (field.required && !value) errors[field.name] = t.required
      if (field.type === 'number' && value && Number(value) < 1) errors[field.name] = t.required
    })
  })

  const today = new Date().toISOString().slice(0, 10)
  if (values.dateOfBirth && values.dateOfBirth > today) errors.dateOfBirth = t.futureDate
  if (values.dateOfIssue && values.expiryDate && values.expiryDate < values.dateOfIssue) {
    errors.expiryDate = t.dateOrder
  }
  if (values.intendedDateOfEntry && values.intendedDateOfEntry < today) {
    errors.intendedDateOfEntry = t.futureDate
  }
  const passportErr = validatePassportNo(values, t)
  if (passportErr) errors.passportNo = passportErr
  if (!String(values.signature || '').trim()) errors.signature = t.required
  if (!values.agree) errors.agree = t.agreeRequired

  return errors
}

// 生成中英对照的纯文本摘要，用于邮件正文与复制
export function buildSummary(values, lang) {
  const lines = []
  lines.push('老挝签证申请表 / Laos Visa Application Form')
  lines.push('========================================')

  sections.forEach((section) => {
    lines.push('')
    lines.push(`【${section.id === 'personal' ? '个人信息' : section.id === 'passport' ? '护照信息' : '旅行信息'}】`)
    section.fields.forEach((field) => {
      const raw = values[field.name]
      let value = raw
      if (field.type === 'select' && raw) {
        const list = options[field.options] || []
        const opt = list.find((item) => item.value === raw)
        value = opt ? (lang === 'zh' ? `${opt.zh} (${opt.en})` : opt.en) : raw
      }
      lines.push(`${field.label.zh.replace(' *', '')} / ${field.label.en.replace(' *', '')}: ${value || '—'}`)
    })
  })

  lines.push('')
  lines.push(`声明 / Declaration: ${values.agree ? (lang === 'zh' ? '已同意' : 'Accepted') : '—'}`)
  lines.push(`签名 / Signature: ${values.signature || '—'}`)
  lines.push(`填表日期 / Date: ${values.formDate || '—'}`)
  lines.push('')
  lines.push('Generated by Laos Visa Form')

  return lines.join('\n')
}
